function doubleValue(num) {
  return num * 2; // ভেতরে শুধু ক্যালকুলেশন করে ফলাফল রিটার্ন করা হলো
}

let originalNumber = 5;

// প্রয়োজন হলে মূল ভ্যারিয়েবলে নতুন মান অ্যাসাইন করা
originalNumber = doubleValue(originalNumber); 

console.log(originalNumber); // আউটপুট: 10 (মান সফলভাবে আপডেট হলো)





  


